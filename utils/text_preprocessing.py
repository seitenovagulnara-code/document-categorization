"""
Этапы 2-3 — Предобработка текста.

Важно: предобработка РАЗВЕТВЛЯЕТСЯ по моделям.
  - basic_clean()        — общая базовая очистка для ВСЕХ (сразу после загрузки).
  - detect_language()    — определение языка (нужно тегировщику на этапе 7).
  - classic_preprocess() — тяжёлая чистка ТОЛЬКО для бейзлайна TF-IDF
                           (нижний регистр, стоп-слова, лемматизация).
  - для DistilBERT классический препроцессинг НЕ применяется:
    у него свой субсловный токенизатор, агрессивная чистка вредит.

По итогам EDA (этап 2): данные почти чистые, пустых нет, поэтому базовая
очистка минимальна — нормализация пробелов и склейка разбитых аббревиатур
(«b. b. c.» -> «bbc»).
"""

import re

# «b. b. c.» / «u. s. a.» -> склеить одиночные буквы через точки в аббревиатуру.
# Матчим первую «букву.» и один-или-более «(пробел?)букву.», НЕ захватывая
# завершающий пробел (иначе склеится со следующим словом).
_ABBREV = re.compile(r"\b[a-zA-Zа-яА-Я]\.(?:\s*[a-zA-Zа-яА-Я]\.)+")


def _join_abbrev(match: str) -> str:
    letters = re.findall(r"[a-zA-Zа-яА-Я]", match.group(0))
    return "".join(letters)


def basic_clean(text: str) -> str:
    """
    Общая базовая очистка (для всех путей):
      - привести буквенные аббревиатуры вида «b. b. c.» к «bbc»,
      - схлопнуть повторяющиеся пробелы,
      - убрать пробелы по краям.
    """
    if not isinstance(text, str):
        return ""
    text = _ABBREV.sub(_join_abbrev, text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def detect_language(text: str) -> str:
    """
    Определить язык текста ('en' / 'ru' / ...). Нужно для маршрутизации
    моделей spaCy в тегировщике (этап 7).
    """
    from langdetect import detect  # импорт внутри — модуль грузится без langdetect
    try:
        return detect(text)
    except Exception:
        return "unknown"


def classic_preprocess(text: str, lang: str = None) -> str:
    """
    Лёгкий препроцессинг для TF-IDF-бейзлайна: базовая очистка + нижний регистр.

    Стоп-слова НЕ удаляем и НЕ лемматизируем намеренно: тексты короткие
    (медиана ~6 слов) и двуязычные, поэтому агрессивная чистка выбрасывает
    полезный сигнал. Параметр lang оставлен для совместимости сигнатуры.
    """
    return basic_clean(text).lower()
